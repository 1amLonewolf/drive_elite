import type { Car, PackageType } from '@/types'
import { getCarImageSync } from '@/composables/useCarImages'

/**
 * Generate image URLs for a single car entry (sync for static data)
 */
function carImages(brand: string, model: string, year: number, type: string, count = 3): string[] {
  return Array.from({ length: count }, (_, i) =>
    getCarImageSync(brand, model, year, type, i)
  )
}

/**
 * Helper to assign package based on KES price
 * Kenyan market realistic tiers:
 * - Go: budget commuters (KSh 3K-7K)
 * - Premium: family & everyday upgrade (KSh 7K-15K)
 * - Elite: business class luxury (KSh 15K-30K)
 * - Exotic: ultra-luxury showstoppers (KSh 30K+)
 */
function pkg(price: number): PackageType {
  if (price <= 7000) return 'go'
  if (price <= 16000) return 'premium'
  if (price <= 35000) return 'elite'
  return 'exotic'
}

